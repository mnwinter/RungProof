def main():
    doc=json.loads(CATALOG.read_text(encoding="utf-8")); rows=[]
    for index,asset in enumerate(doc["assets"],1):
        confidence,evidence_file=RESULTS[asset["id"]];passed=confidence>=.80
        asset["quality"]["blindReviewId"]=f"blind-2026-09-17-rerun-image-{index:03d}"
        asset["quality"]["recognitionConfidence"]=confidence
        # Independent recognition alone never promotes a candidate.
        asset["quality"]["status"]="candidate"
        evidence_path=REPORT.parent/evidence_file
        if not evidence_path.exists():raise FileNotFoundError(evidence_path)
        rows.append({"image":f"image_{index:03d}.png","assetId":asset["id"],"confidence":confidence,"semanticPass":passed,"evidenceFile":evidence_file,"review":evidence_path.read_text(encoding="utf-8").strip()})
