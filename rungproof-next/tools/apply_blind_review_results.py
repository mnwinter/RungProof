    REPORT.write_text(json.dumps({"reviewId":"blind-2026-09-17-rerun","reviewerModel":"isolated gpt-5.6-luna and gpt-5.6-sol processes","contextFree":True,"minimumConfidence":.80,"passed":sum(r["semanticPass"] for r in rows),"failed":sum(not r["semanticPass"] for r in rows),"results":rows},indent=2)+"\n",encoding="utf-8")
